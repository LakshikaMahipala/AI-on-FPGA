"""Write weights, test images and expected predictions as hex files for $readmemh.

By default the weights are random (enough to verify the hardware maths). After
training, pass --weights model/exported_weights.npz to use the real network.

    python gen_vectors.py --out ../vectors [--weights ../model/exported_weights.npz]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from cnn_ref import N_FEAT, expected_cycles, forward
from config import C_OUT, IMG, K, N_CLASSES


def write_hex(path: Path, values, bits: int) -> None:
    mask, digits = (1 << bits) - 1, bits // 4
    path.write_text("".join(f"{int(v) & mask:0{digits}x}\n" for v in np.asarray(values).ravel()))


def random_weights(rng):
    w_conv = rng.integers(-128, 128, (C_OUT, K, K))
    b_conv = rng.integers(-2000, 2000, C_OUT)
    w_fc = rng.integers(-128, 128, (N_CLASSES, N_FEAT))
    b_fc = rng.integers(-5000, 5000, N_CLASSES)
    return w_conv, b_conv, 8, w_fc, b_fc


def test_images(rng, n):
    imgs = rng.integers(0, 256, (n, IMG, IMG))
    imgs[0] = 0                                                # all black
    imgs[1] = 255                                              # all white
    yy, xx = np.mgrid[0:IMG, 0:IMG]
    imgs[2] = (255 * (xx + yy) / (2 * IMG - 2)).astype(int)    # smooth gradient
    return imgs.astype(np.uint8)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="../vectors")
    ap.add_argument("--weights", help="npz from model/train_and_export.py")
    ap.add_argument("--images", type=int, default=20)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    if args.weights:
        z = np.load(args.weights)
        w_conv, b_conv, shift, w_fc, b_fc = (z["w_conv"], z["b_conv"], int(z["shift"]),
                                             z["w_fc"], z["b_fc"])
    else:
        w_conv, b_conv, shift, w_fc, b_fc = random_weights(rng)

    imgs = test_images(rng, args.images)
    preds = [forward(img, w_conv, b_conv, shift, w_fc, b_fc)[0] for img in imgs]

    write_hex(out / "w_conv.hex", w_conv, 8)
    write_hex(out / "b_conv.hex", b_conv, 32)
    write_hex(out / "w_fc.hex", w_fc, 8)
    write_hex(out / "b_fc.hex", b_fc, 32)
    write_hex(out / "images.hex", imgs, 8)
    write_hex(out / "expected_class.hex", preds, 8)
    (out / "config.svh").write_text(
        "// Generated by golden/gen_vectors.py — do not edit.\n"
        f"`define IMG {IMG}\n`define K {K}\n`define C_OUT {C_OUT}\n`define N_CLASSES {N_CLASSES}\n"
        f"`define SHIFT {shift}\n`define N_IMAGES {args.images}\n"
        f"`define EXPECTED_CYCLES {expected_cycles()}\n")
    print(f"{args.images} images, predicted classes {preds}, "
          f"{expected_cycles()} cycles per image")


if __name__ == "__main__":
    main()
